const FALLBACK = 'file';

/**
 * Devuelve el marcado SVG de un icono.
 *
 * Un nombre desconocido cae en `file` en lugar de dejar un hueco: un icono
 * equivocado se ve y se corrige, un hueco pasa desapercibido.
 *
 * @param {string} name   Nombre Lucide del icono.
 * @param {number} size   Lado en píxeles.
 * @param {string} extra  Clases CSS adicionales.
 */
export function icon(name, size = 16, extra = '') {
  const path = PATHS[name] || PATHS[FALLBACK];
  const cls = extra ? ` ${extra}` : '';
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" ` +
    `viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" ` +
    `stroke-linecap="round" stroke-linejoin="round" class="icon${cls}" ` +
    `aria-hidden="true" focusable="false">${path}</svg>`
  );
}

/** ¿Está este nombre en el juego de iconos? Útil para no pintar a ciegas. */
export function hasIcon(name) {
  return Object.prototype.hasOwnProperty.call(PATHS, name);
}
